// Writes src/fonts/plex-{sans,mono}-{400,600}-{core,rest}.woff2, plex.generated.mjs, rest.css,
// LICENSE-ibm-plex-*.txt and src/fonts.css (plex.generated.d.mts comes from `prepack`) from the pinned @fontsource/ibm-plex-{sans,mono} latin files.
// Core = ASCII plus the punctuation pages use (CORE_EXTRA below): preloaded, 40 KB for all four faces.
// Rest = every other codepoint of the source, loaded on demand through the "OCX Plex * Rest" families.
// The @fontsource packages are devDependencies only: the output is checked in.
// Change the core list here, then rerun: `pnpm --filter @ocx-sh/theme fonts`. A test fails when stale.
import { createHash } from 'node:crypto';
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';
import wawoff2 from 'wawoff2';
import { cmapCodepoints, emptyOutlineCodepoints } from './sfnt.mjs';

const require = createRequire(import.meta.url);
const OUT = fileURLToPath(new URL('../src/fonts/', import.meta.url));
const SRC_DIR = fileURLToPath(new URL('../src/', import.meta.url));
const NOTE =
  'Generated by scripts/generate-fonts.mjs. Do not edit; regenerate with `pnpm --filter @ocx-sh/theme fonts`.';

/** @param {number} a @param {number} b */
const range = (a, b) => Array.from({ length: b - a + 1 }, (_, i) => a + i);
/** ASCII, NBSP, then · © “ ” ‘ ’ – — … × − ↑ ↓ (no Plex face has U+2060; ® ™ ° • live in the rest files). */
const CORE_WANTED = [
  ...range(0x20, 0x7e),
  0xa0,
  0xb7,
  0xa9,
  0x201c,
  0x201d,
  0x2018,
  0x2019,
  0x2013,
  0x2014,
  0x2026,
  0xd7,
  0x2212,
  0x2191,
  0x2193,
];
const FEATURES = [
  'kern',
  'liga',
  'clig',
  'calt',
  'ccmp',
  'locl',
  'mark',
  'mkmk',
  'rlig',
  'rclt',
  'curs',
  'dist',
  // Plex has no tnum (its digits are tabular already). frac, dnom and numr (diagonal-fractions) are left out on purpose:
  // they add 8.8 KB to the four core files. ccmp and mark vanish on their own: no core glyph needs them.
];
/** @param {number} c */
const isExcluded = (c) => c <= 0x1f || (c >= 0x7f && c <= 0x9f) || c === 0xffff;

/** @param {Uint8Array} buf */
const sha = (buf) => createHash('sha256').update(buf).digest('hex');
/** @param {number} n */
const hex = (n) => n.toString(16).toUpperCase();
/** Codepoints → compact CSS unicode-range. @param {number[]} cps */
const toRange = (cps) => {
  const sorted = [...new Set(cps)].sort((a, b) => a - b);
  /** @type {string[]} */
  const parts = [];
  for (let i = 0; i < sorted.length;) {
    let j = i;
    while (j + 1 < sorted.length && sorted[j + 1] === /** @type {number} */ (sorted[j]) + 1) j++;
    parts.push(
      i === j
        ? `U+${hex(/** @type {number} */ (sorted[i]))}`
        : `U+${hex(/** @type {number} */ (sorted[i]))}-${hex(/** @type {number} */ (sorted[j]))}`,
    );
    i = j + 1;
  }
  return parts.join(',');
};

/** @param {Uint8Array} ttf @param {number[]} cps */
const subset = async (ttf, cps) => {
  const out = await subsetFont(ttf, String.fromCodePoint(...cps), {
    targetFormat: 'truetype',
    keepFeatures: FEATURES,
    preserveNameIds: [0, 1, 2, 3, 4, 5, 6, 13, 14],
    // VDMX stays: dropping it changes Plex Mono 600's hinted pixels in Chrome (70 px on the header wordmark).
    dropTables: ['STAT'],
  });
  return Buffer.from(await wawoff2.compress(out));
};

const FAMILIES = { sans: 'Sans', mono: 'Mono' };
/** @type {unknown} */
const sansPkg = JSON.parse(readFileSync(require.resolve('@fontsource/ibm-plex-sans/package.json'), 'utf8'));
const version = String(Reflect.get(Object(sansPkg), 'version'));
/** @type {Record<string, { bytes: number, sha256: string }>} */
const files = {};
/** @type {Record<string, string>} */
const sources = {};
/** @type {Buffer[]} */
const ttfs = [];
for (const family of Object.keys(FAMILIES)) {
  const pkg = dirname(require.resolve(`@fontsource/ibm-plex-${family}/package.json`));
  for (const weight of [400, 600])
    ttfs.push(
      Buffer.from(
        await wawoff2.decompress(readFileSync(join(pkg, 'files', `ibm-plex-${family}-latin-${weight}-normal.woff2`))),
      ),
    );
}
// A codepoint is blank when every face that maps it gives it an empty outline (U+AD is a hyphen in Plex Mono).
const faceSets = ttfs.map((t) => ({ mapped: new Set(cmapCodepoints(t)), blank: new Set(emptyOutlineCodepoints(t)) }));
const BLANK = new Set(
  faceSets
    .flatMap((f) => [...f.blank])
    .filter((c) => !isExcluded(c) && faceSets.every((f) => !f.mapped.has(c) || f.blank.has(c))),
);
/** @type {Set<number>} */
const coreCps = new Set();
/** @type {Set<number>} */
const restCps = new Set();
for (const family of Object.keys(FAMILIES)) {
  const pkg = dirname(require.resolve(`@fontsource/ibm-plex-${family}/package.json`));
  copyFileSync(join(pkg, 'LICENSE'), join(OUT, `LICENSE-ibm-plex-${family}.txt`));
  for (const weight of [400, 600]) {
    const srcName = `ibm-plex-${family}-latin-${weight}-normal.woff2`;
    const src = readFileSync(join(pkg, 'files', srcName));
    sources[srcName] = sha(src);
    const ttf = Buffer.from(await wawoff2.decompress(src));
    const all = cmapCodepoints(ttf).filter((c) => !isExcluded(c));
    // A glyph with no outline (en space, zero-width space) costs a rest file for nothing: core.
    const core = all.filter((c) => CORE_WANTED.includes(c) || BLANK.has(c));
    const rest = all.filter((c) => !core.includes(c));
    core.forEach((c) => coreCps.add(c));
    rest.forEach((c) => restCps.add(c));
    for (const [part, cps] of /** @type {[string, number[]][]} */ ([
      ['core', core],
      ['rest', rest],
    ])) {
      const name = `plex-${family}-${weight}-${part}.woff2`;
      const bytes = await subset(ttf, cps);
      writeFileSync(join(OUT, name), bytes);
      files[name] = { bytes: bytes.length, sha256: sha(bytes) };
    }
  }
}
const CORE_RANGE = toRange([...coreCps]);
const REST_RANGE = toRange([...restCps]);

writeFileSync(
  join(OUT, 'plex.generated.mjs'),
  `// ${NOTE}
/** Version of the @fontsource packages the subsets were cut from. */
export const FONTSOURCE_VERSION = ${JSON.stringify(version)};
/** unicode-range of the preloaded core faces. */
export const CORE_RANGE = ${JSON.stringify(CORE_RANGE)};
/** unicode-range of the on-demand rest faces. */
export const REST_RANGE = ${JSON.stringify(REST_RANGE)};
/** sha256 of each pinned @fontsource source file. */
export const SOURCES = ${JSON.stringify(sources, null, 2)};
/** Byte size and sha256 of each generated file. */
export const FILES = ${JSON.stringify(files, null, 2)};
`,
);
/** @param {string} family @param {string} file @param {number} weight @param {string} unicodeRange @param {string} prefix */
const face = (family, file, weight, unicodeRange, prefix) =>
  `@font-face {
  font-family: '${family}';
  font-style: normal;
  font-display: swap;
  font-weight: ${weight};
  src: url(${prefix}${file}) format('woff2');
  unicode-range: ${unicodeRange};
}
`;
/** @param {string} suffix @param {string} rangeStr @param {string} part @param {string} prefix */
const faces = (suffix, rangeStr, part, prefix) =>
  Object.entries(FAMILIES)
    .flatMap(([family, label]) =>
      [400, 600].map((w) =>
        face(
          `${suffix === 'Rest' ? `OCX Plex ${label} Rest` : `IBM Plex ${label}`}`,
          `plex-${family}-${w}-${part}.woff2`,
          w,
          rangeStr,
          prefix,
        ),
      ),
    )
    .join('');
writeFileSync(join(OUT, 'rest.css'), `/* ${NOTE} */\n${faces('Rest', REST_RANGE, 'rest', './')}`);
writeFileSync(
  join(SRC_DIR, 'fonts.css'),
  `/* ${NOTE}\n * Self-hosted IBM Plex for pages without the Starlight Fonts API: the core faces here (preload them),\n * the rest of latin on demand through the "OCX Plex * Rest" families. */\n@import './fonts/rest.css';\n${faces('Core', CORE_RANGE, 'core', './fonts/')}`,
);
console.log(
  'blank glyphs moved to core:',
  [...BLANK]
    .sort((a, b) => a - b)
    .map((c) => `U+${hex(c)}`)
    .join(' '),
);
console.log(`core ${CORE_RANGE.length} chars of range, rest ${REST_RANGE.length}`);
for (const [n, f] of Object.entries(files)) console.log(n, f.bytes);
