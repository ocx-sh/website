import ocxTheme from '@ocx-sh/theme/starlight';
import { defineConfig } from 'astro/config';
import { withoutLegacyBundles } from './legacy-search.mjs';

export default defineConfig({
  site: 'https://ocx.sh',
  base: '/',
  // Starlight reads it before plugins run, so the theme checks it rather than sets it.
  trailingSlash: 'always',
  devToolbar: { enabled: false },
  integrations: [
    starlight({
      title: 'ocx',
      // Pagefind's UI dies on a merged bundle that 404s: sections still on a legacy origin are not merged.
      plugins: [ocxTheme(), withoutLegacyBundles(new URL('../infra/bunny/legacy.json', import.meta.url))],
      // Explicit: the autogenerated sidebar lists the 404 page, a dead link the layout check rejects.
      sidebar: [
        { label: 'Install', link: '/install/' },
        { label: 'Integrations', link: '/integrations/' },
        { label: 'Apps', link: '/apps/' },
      ],
    }),
  ],
});
